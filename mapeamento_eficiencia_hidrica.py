def preparar_taco(caminho_arquivo_entrada, caminho_arquivo_saida):
    print("Carregando a base da TACO...")
    df = pd.read_excel(caminho_arquivo_entrada)

    # ==========================================
    # O FIX INDESTRUTÍVEL (BUSCA DINÂMICA + POSIÇÃO)
    # ==========================================
    col_nome = None
    col_prot = None

    # 1. Tenta achar pelo nome (mesmo que esteja escrito apenas "alimento" ou "Proteína")
    for col in df.columns:
        if 'alimento' in str(col).lower() or 'descri' in str(col).lower():
            col_nome = col
        if 'rote' in str(col).lower(): # Pega "Proteína", "Proteina", "proteina"
            col_prot = col

    # 2. Se o cabeçalho estiver tão destruído que não achou as palavras, apela para a posição!
    # Na TACO padrão, a coluna 1 (2ª coluna) é o nome e a coluna 5 (6ª coluna) é a proteína.
    if not col_nome:
        col_nome = df.columns[1]
    if not col_prot:
        col_prot = df.columns[5]

    print(f"-> Coluna identificada para o NOME: '{col_nome}'")
    print(f"-> Coluna identificada para a PROTEÍNA: '{col_prot}'")

    # Renomeia as colunas com segurança
    df = df.rename(columns={
        col_nome: 'Produto_PT',
        col_prot: 'Proteina_g'
    })

    # ==========================================
    # CONTINUAÇÃO DO PROCESSAMENTO
    # ==========================================
    # Converte vírgula para ponto e transforma textos (como "Tr" de traços) em nulo
    if df['Proteina_g'].dtype == object:
        df['Proteina_g'] = df['Proteina_g'].astype(str).str.replace(',', '.')
        df['Proteina_g'] = pd.to_numeric(df['Proteina_g'], errors='coerce')

    # Aplica a regra da Anvisa (>= 6g)
    df_fonte_proteina = df[df['Proteina_g'] >= 6.0].copy()
    print(f"\nAlimentos que são fonte de proteína (>=6g) encontrados: {len(df_fonte_proteina)}")

    # Inicia a tradução
    tradutor = GoogleTranslator(source='pt', target='en')

    df_fonte_proteina['Produto_EN'] = df_fonte_proteina['Produto_PT'].progress_apply(
        lambda texto: tradutor.translate(str(texto)) if pd.notna(texto) else None
    )

    # Injeta a coluna para a tabela DIAAS
    df_fonte_proteina['Categoria_Alimento'] = ""

    # Organiza a saída
    colunas_finais = ['Produto_PT', 'Produto_EN', 'Categoria_Alimento', 'Proteina_g']
    outras_colunas = [col for col in df_fonte_proteina.columns if col not in colunas_finais]

    df_final = df_fonte_proteina[colunas_finais + outras_colunas]

    # Salva o arquivo final
    df_final.to_excel(caminho_arquivo_saida, index=False)
    print(f"\nSucesso! Arquivo salvo como: {caminho_arquivo_saida}")

