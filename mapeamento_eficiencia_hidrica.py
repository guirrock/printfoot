import pandas as pd
import numpy as np
from sentence_transformers import SentenceTransformer, util
import torch

# ================================
# 1. CARREGAR OS ARQUIVOS EXCEL E LIMPAR
# ================================
print("Carregando bases de dados...")
taco = pd.read_excel('taco_traduzida.xlsx')
diaas = pd.read_excel('Tabela DIAAS.xlsx')
wf_animais = pd.read_excel('waterstat_animais_limpo.xlsx')
wf_vegetais = pd.read_excel('waterstat_vegetais_limpo.xlsx')

pegada_global = pd.concat([wf_animais, wf_vegetais], ignore_index=True).dropna(subset=['Produto_EN'])
pegada_choices = pegada_global['Produto_EN'].tolist()

taco['Produto_EN'] = taco['Produto_EN'].fillna("").astype(str)
taco['Produto_PT_limpo'] = taco['Produto_PT'].fillna("").astype(str).str.lower()

# ================================
# 2. ANCORAGEM OBRIGATÓRIA (REGRAS RÍGIDAS)
# ================================
# Dicionário mapeando a palavra em PT para a Categoria Mãe exata da WFN
regras_ouro = {
    'carne, bovina': 'Bovine cuts boneless, fresh or chilled',
    'hamburguer': 'Bovine cuts boneless, fresh or chilled',
    'linguica, frango': 'Meat of fowls of the species Gallus domesticus', # Tem que vir antes da regra de 'frango' e 'linguica' geral
    'frango': 'Meat of fowls of the species Gallus domesticus',
    'peru': 'Turkey meat and meat offal prepared or preserved, excluding livers',
    'porco': 'Hams, shoulders and cuts thereof, of swine bone in, fresh or chilled',
    'linguica': 'Swine meat cured, nes',
    'presunto': 'Swine meat cured, nes',
    'leite, de vaca, desnatado': 'Milk powder not exceeding 1.5% fat',
    'leite, de vaca, integral': 'Milk and cream not concentrated and unsweetened exceeding 6% fat',
    'leite, condensado': 'Milk and cream nes sweetened',
    'queijo': 'Cheese nes',
    'ovo': 'Eggs, bird, in shell, fresh, preserved or cooked',
    'arroz': 'Rice, paddy',
    'feijao': 'Beans, dry',
    'trigo': 'Wheat',
    'macarrao': 'Wheat',
    'pao': 'Wheat',
    'aveia': 'Oats',
    'milho': 'Maize',
    'soja': 'Soybeans'
}

print("Aplicando ancoragem rígida para carnes e grãos base...")
taco['Match_WF_Rigido'] = None

for i, row in taco.iterrows():
    nome_pt = row['Produto_PT_limpo']
    for chave_pt, valor_wfn in regras_ouro.items():
        if chave_pt in nome_pt:
            taco.at[i, 'Match_WF_Rigido'] = valor_wfn
            break # Achou a regra, para de procurar

# ================================
# 3. VETORIZAÇÃO SEMÂNTICA (Apenas para os "difíceis")
# ================================
print("Carregando o modelo de IA para analisar os alimentos restantes...")
modelo = SentenceTransformer('all-MiniLM-L6-v2')
embeddings_wfn = modelo.encode(pegada_choices, convert_to_tensor=True)

print("Calculando IA Semântica...")
for i, row in taco.iterrows():
    # Se já foi resolvido pela regra rígida, pula o cálculo da IA e dá Score 100%
    if pd.notna(row['Match_WF_Rigido']):
        taco.at[i, 'Match_Final_WFN'] = row['Match_WF_Rigido']
        taco.at[i, 'Score_Confianca'] = 100.0
    else:
        # Se não tem regra, a IA vetorial entra em ação
        embedding_query = modelo.encode(row['Produto_EN'], convert_to_tensor=True)
        cos_score = util.cos_sim(embedding_query, embeddings_wfn)[0]

        melhor_idx = torch.argmax(cos_score).item()
        melhor_score = cos_score[melhor_idx].item() * 100

        taco.at[i, 'Match_Final_WFN'] = pegada_choices[melhor_idx]
        taco.at[i, 'Score_Confianca'] = round(melhor_score, 2)

# ================================
# 4. EXPORTAR TABELA DE REVISÃO E APLICAR MATCH DE PESCADOS
# ================================
# Limpa Pescados que a IA tentou adivinhar (Pescados não têm pegada hídrica medida pela WFN)
palavras_peixe = ['pescada', 'salmao', 'sardinha', 'lambari', 'abadejo', 'atum', 'bacalhau', 'cacao', 'camarao', 'caranguejo', 'corimba', 'corvina', 'dourada', 'manjuba', 'merluza', 'pintado', 'porquinho', 'tucunare']
for i, row in taco.iterrows():
    if any(peixe in row['Produto_PT_limpo'] for peixe in palavras_peixe):
        taco.at[i, 'Match_Final_WFN'] = None
        taco.at[i, 'Score_Confianca'] = 0.0

correspondencias = taco[['Produto_PT', 'Produto_EN', 'Match_Final_WFN', 'Score_Confianca']].sort_values(by='Score_Confianca', ascending=True)
correspondencias.to_excel('1_revisao_hibrida.xlsx', index=False)
print("Tabela de revisão gerada: '1_revisao_hibrida.xlsx'")

# ================================
# 5. MERGE MÚLTIPLO: TACO + PEGADA + DIAAS
# ================================
print("Realizando os cruzamentos de dados finais...")
df = pd.merge(taco, pegada_global, left_on='Match_Final_WFN', right_on='Produto_EN', how='inner')

df['Categoria_Alimento'] = df['Categoria_Alimento'].astype(str).str.strip()
diaas['Categoria_Alimento'] = diaas['Categoria_Alimento'].astype(str).str.strip()
df = pd.merge(df, diaas, on='Categoria_Alimento', how='left')
df['DIAAS'] = pd.to_numeric(df['DIAAS'], errors='coerce').fillna(50.0)

# ================================
# 6. CÁLCULO DAS EFICIÊNCIAS E EXPORTAÇÃO
# ================================
df['Proteina_g'] = pd.to_numeric(df['Proteina_g'], errors='coerce')
df['Agua_Total_m3_t'] = pd.to_numeric(df['Agua_Total_m3_t'], errors='coerce')
df = df.dropna(subset=['Proteina_g', 'Agua_Total_m3_t'])

df['Eficiencia_Bruta_g_m3'] = df['Proteina_g'] / df['Agua_Total_m3_t']
df['Proteina_Digestivel_g'] = df['Proteina_g'] * (df['DIAAS'] / 100)
df['Eficiencia_Real_g_m3'] = df['Proteina_Digestivel_g'] / df['Agua_Total_m3_t']

colunas_finais = [
    'Produto_PT', 'Match_Final_WFN', 'Score_Confianca', 'Categoria_Alimento',
    'Proteina_g', 'DIAAS', 'Proteina_Digestivel_g',
    'Agua_Verde', 'Agua_Azul', 'Agua_Cinza', 'Agua_Total_m3_t',
    'Eficiencia_Bruta_g_m3', 'Eficiencia_Real_g_m3'
]

df_final = df[colunas_finais].sort_values(by='Eficiencia_Real_g_m3', ascending=False)
df_final.to_excel('2_eficiencia_proteica_real_hibrida.xlsx', index=False)
