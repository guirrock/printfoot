import pandas as pd

def limpar_planilha_wfn(caminho_arquivo, linha_inicio, col_produto, col_tipo_agua, col_valor_alvo):
    """
    Função para ler e limpar as planilhas brutas da Water Footprint Network.
    """
    print(f"Processando arquivo: {caminho_arquivo}...")

    # 1. Carrega o arquivo ignorando os cabeçalhos complexos
    # header=None força o pandas a tratar as colunas como números (0, 1, 2, 3...)
    df_raw = pd.read_excel(caminho_arquivo, header=None, skiprows=linha_inicio)

    # 2. Isola apenas as 3 colunas que importam
    df = df_raw[[col_produto, col_tipo_agua, col_valor_alvo]].copy()
    df.columns = ['Produto', 'Tipo_Agua', 'Valor']

    # 3. Limpeza de texto para evitar erros de digitação ocultos no Excel
    df['Tipo_Agua'] = df['Tipo_Agua'].astype(str).str.strip().str.capitalize()
    df['Produto'] = df['Produto'].astype(str).str.strip()

    # Transforma strings vazias ou 'nan' em valores nulos reais do Pandas
    df.loc[df['Produto'] == 'nan', 'Produto'] = None
    df.loc[df['Produto'] == '', 'Produto'] = None

    # 4. O PULO DO GATO: Forward Fill (ffill)
    # Preenche os nomes de produtos vazios com o nome do produto da linha de cima
    df['Produto'] = df['Produto'].ffill()

    # 5. Filtra apenas as linhas que contêm os dados de água
    df = df[df['Tipo_Agua'].isin(['Green', 'Blue', 'Grey'])]

    # Converte a coluna de valores para números (transforma erros ou hífens em NaN)
    df['Valor'] = pd.to_numeric(df['Valor'], errors='coerce').fillna(0)

    # 6. Dinâmica de Tabela (Pivot)
    # Transforma as linhas Green, Blue e Grey em colunas
    df_clean = df.pivot_table(
        index='Produto',
        columns='Tipo_Agua',
        values='Valor',
        aggfunc='first'
    ).reset_index()

    # 7. Formatação Final
    df_clean.columns.name = None # Remove o nome do índice do pivot

    # Garante que todas as colunas existam mesmo se faltar algum dado
    for cor in ['Green', 'Blue', 'Grey']:
        if cor not in df_clean.columns:
            df_clean[cor] = 0.0

    df_clean = df_clean.rename(columns={
        'Produto': 'Produto_EN',
        'Green': 'Agua_Verde',
        'Blue': 'Agua_Azul',
        'Grey': 'Agua_Cinza'
    })

    # Cria a coluna final de totalização
    df_clean['Agua_Total_m3_t'] = df_clean['Agua_Verde'] + df_clean['Agua_Azul'] + df_clean['Agua_Cinza']

    print(f"Sucesso! {len(df_clean)} produtos extraídos.")
    return df_clean[['Produto_EN', 'Agua_Verde', 'Agua_Azul', 'Agua_Cinza', 'Agua_Total_m3_t']]

